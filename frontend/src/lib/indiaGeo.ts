interface Poly { ring: Ring; lat0: number; lat1: number; lon0: number; lon1: number }
const poly = (ring: Ring): Poly => ({
  ring,
  lat0: Math.min(...ring.map((p) => p[0])), lat1: Math.max(...ring.map((p) => p[0])),
  lon0: Math.min(...ring.map((p) => p[1])), lon1: Math.max(...ring.map((p) => p[1])),
});

function inside(p: Poly, lat: number, lon: number): boolean {
  if (lat < p.lat0 || lat > p.lat1 || lon < p.lon0 || lon > p.lon1) return false;
  const r = p.ring;
  let hit = false;
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
    const [ai, bi] = r[i], [aj, bj] = r[j];
    if ((ai > lat) !== (aj > lat) && lon < ((bj - bi) * (lat - ai)) / (aj - ai) + bi) hit = !hit;
  }
  return hit;
}

const P_MAINLAND = poly(MAINLAND);
const P_SRI_LANKA = poly(SRI_LANKA);
const P_ISLANDS = INDIAN_ISLANDS.map(poly);
const P_INDIA = poly(INDIA_MAINLAND);

/** 0 = sea, 1 = neighbouring country, 2 = India. */
export function geoKind(lat: number, lon: number): 0 | 1 | 2 {
  if (inside(P_MAINLAND, lat, lon)) return inside(P_INDIA, lat, lon) ? 2 : 1;
  if (inside(P_SRI_LANKA, lat, lon)) return 1;
  for (const p of P_ISLANDS) if (inside(p, lat, lon)) return 2;
  return 0;
}
